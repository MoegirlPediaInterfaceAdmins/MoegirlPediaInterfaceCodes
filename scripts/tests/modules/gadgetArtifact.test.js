import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { buildGeneratedFileHeader, writeGadgetArtifact } from "../../modules/gadgetArtifact.js";

// 产物路径落点在写盘全被拦截的前提下仅用于构造参数；每次运行用 mkdtemp 唯一目录，
// 防止上次运行残留的同名产物让「有变更」用例被误判为内容一致
let artifactBase;

beforeAll(async () => {
    artifactBase = await fs.promises.mkdtemp(path.join(os.tmpdir(), "gadgetArtifact-test-"));
});

afterAll(async () => {
    await fs.promises.rm(artifactBase, { recursive: true, force: true });
});

beforeEach(() => {
    // 拦截真实写盘：spy 默认会透传原实现，必须显式替换为空实现
    vi.spyOn(fs.promises, "writeFile").mockResolvedValue(undefined);
    vi.spyOn(fs.promises, "mkdir").mockResolvedValue(undefined);
});

afterEach(() => {
    vi.restoreAllMocks();
});

describe("buildGeneratedFileHeader", () => {
    it("由 Generated by 来源、Options 项与首尾注释行组成", () => {
        expect(buildGeneratedFileHeader("scripts/buildGadgets.js", { a: 1 })).toEqual([
            "/**",
            " * Generated by scripts/buildGadgets.js",
            " * Options:",
            " *     a: 1",
            " */",
        ]);
    });

    it("字符串值按 JSON 序列化（保留双引号）", () => {
        const lines = buildGeneratedFileHeader("s.js", { name: "G" });

        expect(lines).toContain(" *     name: \"G\"");
    });

    it("对象值的多行 JSON 序列化压缩为单行", () => {
        const lines = buildGeneratedFileHeader("s.js", { opt: { b: 2 } });

        expect(lines).toContain(" *     opt: { \"b\": 2 }");
    });

    it("数组值的多行 JSON 序列化压缩为单行", () => {
        const lines = buildGeneratedFileHeader("s.js", { list: [1, 2] });

        expect(lines).toContain(" *     list: [ 1, 2 ]");
    });

    it("空选项时仅输出头部三行与结束行", () => {
        expect(buildGeneratedFileHeader("s.js", {})).toEqual([
            "/**",
            " * Generated by s.js",
            " * Options:",
            " */",
        ]);
    });
});

describe("writeGadgetArtifact", () => {
    it("新内容写入：建目录并写入全文（js 与 css 同路径）", async () => {
        const file = path.join(artifactBase, "G", "G.js");
        const code = "/* code */\n";

        await expect(writeGadgetArtifact(file, code)).resolves.toBe(true);

        expect(fs.promises.mkdir).toHaveBeenCalledWith(path.dirname(file), { recursive: true });
        expect(fs.promises.writeFile).toHaveBeenCalledWith(file, code);
    });

    it("磁盘内容一致时返回 false 且不产生任何写操作", async () => {
        const file = path.join(artifactBase, "G", "G.js");
        const code = "/* unchanged */\n";
        vi.spyOn(fs.promises, "readFile").mockResolvedValue(code);

        await expect(writeGadgetArtifact(file, code)).resolves.toBe(false);

        expect(fs.promises.mkdir).not.toHaveBeenCalled();
        expect(fs.promises.writeFile).not.toHaveBeenCalled();
    });

    it("磁盘文件不存在时视为有变更并写入", async () => {
        const file = path.join(artifactBase, "G", "G.css");
        vi.spyOn(fs.promises, "readFile").mockRejectedValue(Object.assign(new Error("ENOENT"), { code: "ENOENT" }));

        await expect(writeGadgetArtifact(file, "body {}")).resolves.toBe(true);

        expect(fs.promises.writeFile).toHaveBeenCalledWith(file, "body {}");
    });
});
